Page({
  data: {
    sections: [],
  },
  onLoad() {
    platform.showShareMenu();
    const mode = api.isLocal() ? 'local' : 'cloud';
    const sections = SECTIONS.filter((s) => !s.only || s.only === mode).map((s, i) => ({ key: i, open: i === 0, title: s.title, steps: s.steps }));
    if (mode === 'cloud') sections[sections.length - 1].steps[0] = '数据保存在云端，换手机也不会丢失。也可以在「备份与恢复」里导出一份备份。';
    this.setData({ sections });
  },
  toggle(e) {
    const i = e.currentTarget.dataset.index;
    this.setData({ [`sections[${i}].open`]: !this.data.sections[i].open });
  },
  onShareAppMessage: share.appMessage,
  onShareTimeline: share.timeline,
});
